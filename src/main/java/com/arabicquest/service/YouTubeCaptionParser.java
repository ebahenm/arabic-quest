// Parses YouTube watch-page caption tracks, JSON3/XML timedtext payloads, and safe HTTPS YouTube URIs.
package com.arabicquest.service;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.net.URI;
import java.util.*;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

final class YouTubeCaptionParser {

    private static final ObjectMapper MAPPER = new ObjectMapper();
    private static final Pattern XML_TEXT_PATTERN = Pattern.compile(
            "<text\\b([^>]*)>(.*?)</text>", Pattern.CASE_INSENSITIVE | Pattern.DOTALL);
    private static final Pattern START_ATTR_PATTERN = Pattern.compile(
            "\\bstart\\s*=\\s*[\"']([0-9.]+)[\"']", Pattern.CASE_INSENSITIVE);
    private static final Pattern NUMERIC_ENTITY_PATTERN = Pattern.compile("&#(x?[0-9A-Fa-f]+);");

    record CaptionCandidate(String baseUrl, String langCode, boolean autoGenerated, int priority) {}
    private record TimedCue(int sec, String text) {}

    private YouTubeCaptionParser() {
    }

    static Optional<String> parseCaptionBody(String body, int minChars, int maxChars) {
        if (body == null || body.isBlank()) {
            return Optional.empty();
        }
        String trimmed = body.trim();
        String parsed = trimmed.startsWith("{") ? parseJson3Captions(trimmed) : parseXmlCaptions(trimmed);
        if (parsed.length() < minChars) {
            return Optional.empty();
        }
        if (parsed.length() > maxChars) {
            parsed = parsed.substring(0, maxChars);
        }
        return Optional.of(parsed);
    }

    static List<CaptionCandidate> extractCaptionTracksFromHtml(String html) {
        int keyIdx = html.indexOf("\"captionTracks\":");
        if (keyIdx < 0) {
            return List.of();
        }
        int arrStart = html.indexOf('[', keyIdx);
        if (arrStart < 0) {
            return List.of();
        }
        String arrayJson = extractBalancedJsonArray(html, arrStart);
        if (arrayJson == null) {
            return List.of();
        }
        try {
            JsonNode arr = MAPPER.readTree(arrayJson);
            if (!arr.isArray()) {
                return List.of();
            }
            List<CaptionCandidate> out = new ArrayList<>();
            for (JsonNode t : arr) {
                String baseUrl = t.path("baseUrl").asText("");
                String lang = t.path("languageCode").asText("");
                boolean asr = "asr".equalsIgnoreCase(t.path("kind").asText(""));
                if (!baseUrl.isBlank()) {
                    out.add(new CaptionCandidate(baseUrl, lang, asr, scoreLanguagePriority(lang, asr)));
                }
            }
            return out;
        } catch (Exception ex) {
            return List.of();
        }
    }

    static int scoreLanguagePriority(String langCode, boolean asr) {
        String l = langCode == null ? "" : langCode.toLowerCase(Locale.ROOT);
        boolean isAr = l.equals("ar") || l.startsWith("ar-");
        boolean isEn = l.equals("en") || l.startsWith("en-");
        if (isAr && !asr) return 0;
        if (isEn && !asr) return 1;
        if (isAr) return 2;
        if (isEn) return 3;
        return asr ? 5 : 4;
    }

    static boolean isAllowedYouTubeUri(String rawUrl) {
        try {
            URI uri = URI.create(rawUrl);
            String host = uri.getHost() == null ? "" : uri.getHost().toLowerCase(Locale.ROOT);
            return "https".equalsIgnoreCase(uri.getScheme())
                    && (host.equals("youtube.com") || host.endsWith(".youtube.com") || host.equals("video.google.com"));
        } catch (Exception ex) {
            return false;
        }
    }

    private static String parseJson3Captions(String json) {
        try {
            JsonNode events = MAPPER.readTree(json).path("events");
            if (!events.isArray()) {
                return "";
            }
            List<TimedCue> cues = new ArrayList<>();
            for (JsonNode ev : events) {
                JsonNode segs = ev.path("segs");
                if (!segs.isArray()) {
                    continue;
                }
                StringBuilder line = new StringBuilder();
                for (JsonNode seg : segs) {
                    line.append(seg.path("utf8").asText(""));
                }
                int sec = Math.max(0, (int) (ev.path("tStartMs").asLong(0L) / 1000L));
                String text = normalizeCueText(line.toString());
                if (!text.isEmpty()) {
                    cues.add(new TimedCue(sec, text));
                }
            }
            return formatTimedCues(cues);
        } catch (Exception ex) {
            return "";
        }
    }

    private static String parseXmlCaptions(String xml) {
        List<TimedCue> cues = new ArrayList<>();
        Matcher m = XML_TEXT_PATTERN.matcher(xml);
        while (m.find()) {
            String attrs = m.group(1);
            int sec = 0;
            Matcher sm = START_ATTR_PATTERN.matcher(attrs != null ? attrs : "");
            if (sm.find()) {
                try {
                    sec = Math.max(0, (int) Math.floor(Double.parseDouble(sm.group(1))));
                } catch (NumberFormatException ignored) {}
            }
            String text = normalizeCueText(m.group(2));
            if (!text.isEmpty()) {
                cues.add(new TimedCue(sec, text));
            }
        }
        return formatTimedCues(cues);
    }

    private static String extractBalancedJsonArray(String text, int startIdx) {
        int depth = 0;
        boolean inStr = false;
        boolean escaped = false;
        for (int i = startIdx; i < text.length(); i++) {
            char c = text.charAt(i);
            if (escaped) {
                escaped = false;
                continue;
            }
            if (inStr) {
                if (c == '\\') escaped = true;
                else if (c == '"') inStr = false;
                continue;
            }
            if (c == '"') inStr = true;
            else if (c == '[') depth++;
            else if (c == ']' && --depth == 0) {
                return text.substring(startIdx, i + 1);
            }
        }
        return null;
    }

    private static String formatTimedCues(List<TimedCue> cues) {
        StringBuilder sb = new StringBuilder();
        String prev = "";
        int lastStampSec = -30;
        for (TimedCue cue : cues) {
            if (cue.text().equalsIgnoreCase(prev)) {
                continue;
            }
            prev = cue.text();
            if (cue.sec() - lastStampSec >= 20) {
                if (sb.length() > 0) sb.append('\n');
                sb.append('[').append(cue.sec() / 60).append(':').append(String.format("%02d", cue.sec() % 60)).append("] ");
                lastStampSec = cue.sec();
            } else if (sb.length() > 0) {
                sb.append(' ');
            }
            sb.append(cue.text());
        }
        return sb.toString().trim();
    }

    private static String normalizeCueText(String raw) {
        if (raw == null || raw.isBlank()) {
            return "";
        }
        String unescaped = unescapeHtml(raw).replaceAll("<[^>]+>", " ");
        return unescaped.replace('\r', ' ').replace('\n', ' ').replaceAll("\\s+", " ").trim();
    }

    private static String unescapeHtml(String raw) {
        String s = raw.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")
                .replace("&quot;", "\"").replace("&#39;", "'").replace("&apos;", "'");
        Matcher m = NUMERIC_ENTITY_PATTERN.matcher(s);
        StringBuilder out = new StringBuilder();
        while (m.find()) {
            String code = m.group(1);
            try {
                int cp = code.startsWith("x") || code.startsWith("X")
                        ? Integer.parseInt(code.substring(1), 16) : Integer.parseInt(code);
                m.appendReplacement(out, Matcher.quoteReplacement(new String(Character.toChars(cp))));
            } catch (Exception e) {
                m.appendReplacement(out, Matcher.quoteReplacement(m.group(0)));
            }
        }
        m.appendTail(out);
        return out.toString();
    }
}
