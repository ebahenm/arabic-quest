// Runs @Async quiz bank generation jobs on the background executor and tags auto-approved questions with source=AUTO.
package com.arabicquest.service;

import com.arabicquest.model.EpisodeTranscript;
import com.arabicquest.model.OpenQuestion;
import com.arabicquest.model.Question;
import com.arabicquest.model.QuestionStatus;
import com.arabicquest.repository.EpisodeRepository;
import com.arabicquest.repository.EpisodeTranscriptRepository;
import com.arabicquest.repository.OpenQuestionRepository;
import com.arabicquest.repository.QuestionRepository;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.annotation.Lazy;
import org.springframework.scheduling.annotation.Async;
import org.springframework.stereotype.Service;
import org.springframework.transaction.support.TransactionTemplate;

import java.util.Optional;
import java.util.concurrent.CompletableFuture;

@Service
public class AutoQuizAsyncWorker {

    private static final Logger log = LoggerFactory.getLogger(AutoQuizAsyncWorker.class);

    private final AiQuizService aiQuizService;
    private final EpisodeTranscriptRepository transcriptRepository;
    private final EpisodeRepository episodeRepository;
    private final QuestionRepository questionRepository;
    private final OpenQuestionRepository openQuestionRepository;
    private final TransactionTemplate transactionTemplate;

    @Autowired
    public AutoQuizAsyncWorker(
            @Lazy AiQuizService aiQuizService,
            EpisodeTranscriptRepository transcriptRepository,
            EpisodeRepository episodeRepository,
            QuestionRepository questionRepository,
            OpenQuestionRepository openQuestionRepository,
            TransactionTemplate transactionTemplate) {
        this.aiQuizService = aiQuizService;
        this.transcriptRepository = transcriptRepository;
        this.episodeRepository = episodeRepository;
        this.questionRepository = questionRepository;
        this.openQuestionRepository = openQuestionRepository;
        this.transactionTemplate = transactionTemplate;
    }

    @Async("quizAutoGenExecutor")
    public CompletableFuture<AiQuizService.GeneratedBankSummary> executeAutoGeneration(
            Long episodeId,
            boolean topUpMode,
            Runnable releaseLock) {
        try {
            if (transcriptRepository != null) {
                Optional<EpisodeTranscript> opt = transcriptRepository.findByEpisodeId(episodeId);
                if (opt.isPresent() && !opt.get().isUsableForGeneration()) {
                    episodeRepository.findById(episodeId).ifPresent(ep -> {
                        if (ep.getTranscriptText() != null) {
                            ep.setTranscriptText(null);
                            episodeRepository.save(ep);
                        }
                    });
                }
            }
            AiQuizService.GeneratedBankSummary summary = aiQuizService.generateQuestionBankForEpisode(
                    null,
                    episodeId,
                    null,
                    true,
                    topUpMode
            );
            tagAutoGeneratedQuestions(episodeId);
            return CompletableFuture.completedFuture(summary);
        } catch (Exception ex) {
            log.warn("Background auto-generation skipped/failed for episode {}: {}", episodeId, ex.getMessage());
            return CompletableFuture.completedFuture(null);
        } finally {
            if (releaseLock != null) {
                releaseLock.run();
            }
        }
    }

    private void tagAutoGeneratedQuestions(Long episodeId) {
        if (transactionTemplate == null || questionRepository == null) return;
        transactionTemplate.executeWithoutResult(st -> {
            for (Question q : questionRepository.findByEpisodeIdWithOptions(episodeId)) {
                if (q.getSource() == null && q.getStatus() == QuestionStatus.APPROVED) {
                    q.setSource("AUTO");
                    questionRepository.save(q);
                }
            }
            if (openQuestionRepository != null) {
                for (OpenQuestion oq : openQuestionRepository.findByEpisodeIdOrderByIdAsc(episodeId)) {
                    if (oq.getSource() == null && oq.getStatus() == QuestionStatus.APPROVED) {
                        oq.setSource("AUTO");
                        openQuestionRepository.save(oq);
                    }
                }
            }
        });
    }
}
