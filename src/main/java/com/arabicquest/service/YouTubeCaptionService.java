// Automatically fetches Arabic/English YouTube captions via timedtext tracks or YouTube Data API v3.
package com.arabicquest.service;

import com.arabicquest.service.YouTubeCaptionParser.CaptionCandidate;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.http.*;
import org.springframework.http.client.SimpleClientHttpRequestFactory;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestTemplate;
import org.springframework.web.util.UriComponentsBuilder;

import java.net.URI;
import java.util.*;
import java.util.regex.Pattern;

@Service
public class YouTubeCaptionService {

    private static final Logger log = LoggerFactory.getLogger(YouTubeCaptionService.class);
    private static final Pattern VIDEO_ID_PATTERN = Pattern.compile("^[A-Za-z0-9_-]{6,30}$");
    private static final int MIN_TRANSCRIPT_CHARS = 40;

    private final ObjectMapper objectMapper = new ObjectMapper();
    private RestTemplate restTemplate = createShortTimeoutRestTemplate();

    @Value("${YOUTUBE_API_KEY:}")
    private String youtubeApiKey;

    @Value("${app.youtube.captions.enabled:true}")
    private boolean enabled = true;

    public void setRestTemplate(RestTemplate restTemplate) {
        this.restTemplate = restTemplate;
    }

    public RestTemplate getRestTemplate() {
        return restTemplate;
    }

    public void setYoutubeApiKey(String youtubeApiKey) {
        this.youtubeApiKey = youtubeApiKey;
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
    }

    private static RestTemplate createShortTimeoutRestTemplate() {
        SimpleClientHttpRequestFactory factory = new SimpleClientHttpRequestFactory();
        factory.setConnectTimeout(4_000);
        factory.setReadTimeout(6_000);
        return new RestTemplate(factory);
    }

    public Optional<String> fetchCaptionsTranscript(String videoId) {
        if (!enabled || videoId == null || !VIDEO_ID_PATTERN.matcher(videoId.trim()).matches()) {
            return Optional.empty();
        }
        String cleanId = videoId.trim();
        Optional<String> fromWatchPage = fetchFromWatchPageTracks(cleanId);
        if (fromWatchPage.isPresent()) {
            return fromWatchPage;
        }
        return fetchFromTimedTextOrDataApi(cleanId);
    }

    private Optional<String> fetchFromWatchPageTracks(String videoId) {
        try {
            HttpHeaders headers = browserHeaders();
            ResponseEntity<String> res = restTemplate.exchange(
                    "https://www.youtube.com/watch?v=" + videoId + "&hl=en",
                    HttpMethod.GET,
                    new HttpEntity<>(headers),
                    String.class
            );
            String html = res.getBody();
            if (html == null || html.isBlank()) {
                return Optional.empty();
            }
            List<CaptionCandidate> tracks = new ArrayList<>(YouTubeCaptionParser.extractCaptionTracksFromHtml(html));
            if (tracks.isEmpty()) {
                return Optional.empty();
            }
            tracks.sort(Comparator.comparingInt(CaptionCandidate::priority));
            for (CaptionCandidate track : tracks) {
                Optional<String> parsed = fetchAndParseTrackUrl(track.baseUrl(), headers);
                if (parsed.isPresent()) {
                    log.info("Auto-fetched YouTube captions from watch page for {} (lang={}, asr={})",
                            videoId, track.langCode(), track.autoGenerated());
                    return parsed;
                }
            }
        } catch (Exception ex) {
            log.debug("Watch-page caption fetch unavailable for {}: {}", videoId, ex.getClass().getSimpleName());
        }
        return Optional.empty();
    }

    private Optional<String> fetchFromTimedTextOrDataApi(String videoId) {
        List<CaptionCandidate> probes = new ArrayList<>();
        if (youtubeApiKey != null && !youtubeApiKey.isBlank()) {
            try {
                HttpHeaders apiHeaders = new HttpHeaders();
                apiHeaders.set("X-Goog-Api-Key", youtubeApiKey.trim());
                URI apiUri = UriComponentsBuilder.fromUriString("https://www.googleapis.com/youtube/v3/captions")
                        .queryParam("part", "snippet")
                        .queryParam("videoId", videoId)
                        .build().encode().toUri();
                ResponseEntity<String> res = restTemplate.exchange(
                        apiUri, HttpMethod.GET, new HttpEntity<>(apiHeaders), String.class);
                if (res.getBody() != null) {
                    JsonNode items = objectMapper.readTree(res.getBody()).path("items");
                    if (items.isArray()) {
                        for (JsonNode item : items) {
                            String lang = item.path("snippet").path("language").asText("");
                            boolean asr = "ASR".equalsIgnoreCase(item.path("snippet").path("trackKind").asText(""));
                            if (!lang.isBlank()) {
                                String url = "https://www.youtube.com/api/timedtext?v=" + videoId
                                        + "&lang=" + lang + (asr ? "&kind=asr" : "") + "&fmt=json3";
                                probes.add(new CaptionCandidate(
                                        url, lang, asr, YouTubeCaptionParser.scoreLanguagePriority(lang, asr)));
                            }
                        }
                    }
                }
            } catch (Exception ex) {
                log.debug("YouTube Data API caption metadata lookup skipped for {}: {}",
                        videoId, ex.getClass().getSimpleName());
            }
        }
        if (probes.isEmpty()) {
            return Optional.empty();
        }
        probes.sort(Comparator.comparingInt(CaptionCandidate::priority));
        HttpHeaders headers = browserHeaders();
        for (CaptionCandidate probe : probes) {
            Optional<String> parsed = fetchAndParseTrackUrl(probe.baseUrl(), headers);
            if (parsed.isPresent()) {
                log.info("Auto-fetched YouTube timedtext captions for {} (lang={})", videoId, probe.langCode());
                return parsed;
            }
        }
        return Optional.empty();
    }

    private Optional<String> fetchAndParseTrackUrl(String rawUrl, HttpHeaders headers) {
        try {
            if (!YouTubeCaptionParser.isAllowedYouTubeUri(rawUrl)) {
                return Optional.empty();
            }
            String requestUrl = rawUrl.contains("fmt=") ? rawUrl
                    : rawUrl + (rawUrl.contains("?") ? "&" : "?") + "fmt=json3";
            ResponseEntity<String> res = restTemplate.exchange(
                    URI.create(requestUrl), HttpMethod.GET, new HttpEntity<>(headers), String.class);
            return YouTubeCaptionParser.parseCaptionBody(
                    res.getBody(), MIN_TRANSCRIPT_CHARS, AiQuizService.MAX_TRANSCRIPT_CHARS);
        } catch (Exception ex) {
            return Optional.empty();
        }
    }

    private static HttpHeaders browserHeaders() {
        HttpHeaders h = new HttpHeaders();
        h.set("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/126.0.0.0 Safari/537.36");
        h.set("Accept-Language", "ar,en-US;q=0.9,en;q=0.8");
        h.set("Cookie", "CONSENT=YES+cb");
        return h;
    }
}
